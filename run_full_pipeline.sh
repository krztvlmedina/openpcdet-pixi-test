#!/usr/bin/env bash
# run_full_pipeline.sh — Master pipeline: downsample → infos → interpolate → evaluate → report
#
# Executes all steps sequentially and organises outputs under:
#
#   <host>/../datos/output_runs/<TIMESTAMP>/    (= /OpenPCDet/output_runs/<TIMESTAMP>/ in openpcdet)
#     raw_results/
#       desempeno_offline/
#         original/        ← eval results for original KITTI
#         downsampled/     ← eval results for reduced-kitti
#         interpolated/    ← eval results per interpolation config
#         detections/      ← save_detections.py output (per dataset/model)
#       desempeno_online/  ← run_realtime_eval.sh output
#     latex/
#       desempeno_offline/ ← AP + recall tables
#       desempeno_online/  ← aggregated realtime results
#
# Container volume layout (from compose.yml):
#
#   velodyne_ros2 (CONTAINER_VELODYNE):
#     ../datos/kitti/                          → /app/data/kitti
#     ../datos/reduced-kitti/                  → /app/data/reduced-kitti
#     <ext>/interpolated-kitti/                → /app/data/output/interpolated-kitti  (rw)
#     ./data/config_files/interpolation/       → /app/data/config_files/interpolation/
#     scripts baked into image                 → /app/packages/pointcloud_utils/scripts/
#
#   velodyne_openpcdet (CONTAINER_OPENPCDET):
#     ../datos/kitti/training                  → /OpenPCDet/data/original-kitti/training
#     ../datos/kitti/testing                   → /OpenPCDet/data/original-kitti/testing
#     ../datos/kitti/ImageSets                 → /OpenPCDet/data/original-kitti/ImageSets
#     ../datos/kitti/gt_database               → /OpenPCDet/data/original-kitti/gt_database
#     ../datos/kitti/db_infos                  → /OpenPCDet/data/original-kitti/db_infos
#     ../datos/reduced-kitti/                  → /OpenPCDet/data/reduced-kitti           (rw)
#     ../datos/reduced-kitti/gt_database       → /OpenPCDet/data/reduced-kitti/gt_database
#     ../datos/reduced-kitti/db_infos          → /OpenPCDet/data/reduced-kitti/db_infos/
#     <ext>/interpolated-kitti/                → /OpenPCDet/data/interpolated-kitti      (ro)
#     ../datos/pretrained-models/              → /OpenPCDet/data/pretrained-models
#     ../datos/output_runs/                    → /OpenPCDet/output_runs
#     ./src/lidar/                             → /OpenPCDet/src/lidar
#
# KITTI data structure expected/created by this pipeline:
#
#   reduced-kitti/
#     training/
#       velodyne/     ← downsampled .bin files (written by step 1)
#       calib/        ← symlink → original-kitti/training/calib   (created by step 2)
#       image_2/      ← symlink → original-kitti/training/image_2  (created by step 2)
#       label_2/      ← symlink → original-kitti/training/label_2  (created by step 2)
#       planes/       ← symlink → original-kitti/training/planes   (if it exists)
#     testing/
#       calib/        ← symlink → original-kitti/testing/calib     (created by step 2)
#       image_2/      ← symlink → original-kitti/testing/image_2   (created by step 2)
#       velodyne/     ← symlink → original-kitti/testing/velodyne  (created by step 2)
#     ImageSets/      ← symlink → original-kitti/ImageSets         (created by step 2)
#     kitti_infos_train.pkl    )
#     kitti_infos_val.pkl      )  generated by create_kitti_infos (step 2)
#     kitti_infos_trainval.pkl )
#     kitti_infos_test.pkl     )
#     kitti_dbinfos_train.pkl  )
#
#   interpolated-kitti/<cfg_name>/
#     training/
#       velodyne/     ← interpolated .bin files (written by step 3)
#
# Usage:
#   ./run_full_pipeline.sh [--skip-downsample] [--skip-infos] [--skip-interp]
#                          [--skip-offline] [--skip-online]
#                          [--single-model M] [--single-config C]
#                          [--rate HZ] [--max-frames N]
set -euo pipefail

# ─── Containers ──────────────────────────────────────────────────────────────
CONTAINER_VELODYNE="${CONTAINER_VELODYNE:-velodyne_ros2}"
CONTAINER_OPENPCDET="${CONTAINER_OPENPCDET:-velodyne_openpcdet}"

# ─── Paths inside the velodyne container ─────────────────────────────────────
VEL_SCRIPTS="/app/packages/pointcloud_utils/scripts"
VEL_INTERP_SCRIPT="/app/packages/dynamic_lidar_interpolation/scripts/interpolate_bin_batch.py"
VEL_INTERP_CONFIG_DIR="/app/data/config_files/interpolation/final"
VEL_KITTI_VELODYNE="/app/data/kitti/"
VEL_KITTI_REDUCED="/app/data/reduced-kitti"
VEL_KITTI_INTERP_BASE="/app/data/output/interpolated-kitti"   # read-write

# ─── Paths inside the openpcdet container ────────────────────────────────────
OPC_ROOT="/OpenPCDet"
OPC_DATA="${OPC_ROOT}/data"
OPC_TOOLS="${OPC_ROOT}/src/lidar/tools"
OPC_BATCH="${OPC_TOOLS}/batch_evaluation"

OPC_KITTI_DATA="${OPC_DATA}/original-kitti"
OPC_KITTI_VELODYNE="${OPC_KITTI_DATA}/training/velodyne"   # original 64-beam bins

OPC_KITTI_REDUCED="${OPC_DATA}/reduced-kitti"
OPC_KITTI_REDUCED_VELODYNE="${OPC_KITTI_REDUCED}/training/velodyne"  # downsampled bins

OPC_KITTI_INTERP_BASE="${OPC_DATA}/interpolated-kitti"     # read-only
OPC_PRETRAINED="${OPC_DATA}/pretrained-models"
OPC_RESULTS_BASE="${OPC_ROOT}/output_runs"

# Dataset-info configs (relative to OPC_ROOT, used with python3 -m)
OPC_CFG_ORIGINAL="src/lidar/tools/cfgs/dataset_configs/create_dataset_info_original_kitti_dataset.yaml"
OPC_CFG_REDUCED="src/lidar/tools/cfgs/dataset_configs/create_dataset_info_downsampled_kitti_dataset.yaml"

# Minimum free space in GB required before starting
MIN_FREE_GB=50

# ─── Result root ─────────────────────────────────────────────────────────────
# Host path mirrors the ../datos/output_runs → /OpenPCDet/output_runs mount.
TIMESTAMP=$(date +"%Y%m%d_%H%M%S")
RESULTS_HOST="$(cd "$(dirname "$0")/.." && pwd)/datos/output_runs/${TIMESTAMP}"
RESULTS_OPC="${OPC_RESULTS_BASE}/${TIMESTAMP}"

OFFLINE_RAW="${RESULTS_OPC}/raw_results/desempeno_offline"
ONLINE_RAW="${RESULTS_OPC}/raw_results/desempeno_online"
OFFLINE_LATEX="${RESULTS_OPC}/latex/desempeno_offline"
ONLINE_LATEX="${RESULTS_OPC}/latex/desempeno_online"

# ─── CLI flags ────────────────────────────────────────────────────────────────
SKIP_DOWNSAMPLE=false
SKIP_INFOS=false
SKIP_INTERP=false
SKIP_OFFLINE=false
SKIP_ONLINE=false
SINGLE_MODEL=""
SINGLE_CONFIG=""
PUBLISH_RATE=10.0
MAX_FRAMES=500
WARMUP_FRAMES=10

while [[ $# -gt 0 ]]; do
    case "$1" in
        --skip-downsample) SKIP_DOWNSAMPLE=true; shift ;;
        --skip-infos)      SKIP_INFOS=true;      shift ;;
        --skip-interp)     SKIP_INTERP=true;     shift ;;
        --skip-offline)    SKIP_OFFLINE=true;    shift ;;
        --skip-online)     SKIP_ONLINE=true;     shift ;;
        --single-model)    SINGLE_MODEL="$2";    shift 2 ;;
        --single-config)   SINGLE_CONFIG="$2";   shift 2 ;;
        --rate)            PUBLISH_RATE="$2";    shift 2 ;;
        --max-frames)      MAX_FRAMES="$2";      shift 2 ;;
        *) echo "Unknown option: $1"; exit 1 ;;
    esac
