# ─── Helpers (same pattern as run_realtime_eval.sh) ───────────────────────────
log()  { echo "[$(date +%H:%M:%S)] $*"; }
step() { echo; echo "════════════════════════════════════════════════════════"; \
         echo " $*"; echo "════════════════════════════════════════════════════════"; }


# ─── Step 0: Storage check ───────────────────────────────────────────────────
# Check both mounts: openpcdet (eval outputs) and the external drive where
# interpolated datasets are written (velodyne container, read-write mount).
check_storage() {
    log "Checking available storage..."

    local opc_free
    opc_free=$(docker exec "${CONTAINER_OPENPCDET}" bash -c \
        "df -BG '${OPC_DATA}' | awk 'NR==2{gsub(\"G\",\"\",\$4); print \$4}'")
    log "  [openpcdet] ${OPC_DATA}: ${opc_free} GB free"

    local vel_free
    vel_free=$(docker exec "${CONTAINER_VELODYNE}" bash -c \
        "df -BG '${VEL_KITTI_INTERP_BASE}' | awk 'NR==2{gsub(\"G\",\"\",\$4); print \$4}'")
    log "  [velodyne]  ${VEL_KITTI_INTERP_BASE}: ${vel_free} GB free"

    log "  Minimum required: ${MIN_FREE_GB} GB in each location."
    if [[ "${opc_free}" -lt "${MIN_FREE_GB}" ]]; then
        echo "ERROR: Insufficient storage in openpcdet (${opc_free} GB < ${MIN_FREE_GB} GB)." >&2
        exit 1
    fi
    # if [[ "${vel_free}" -lt "${MIN_FREE_GB}" ]]; then
    #     echo "ERROR: Insufficient storage on external drive (${vel_free} GB < ${MIN_FREE_GB} GB)." >&2
    #     exit 1
    # fi
    log "Storage OK."
}

# ─── Step 1: Downsample KITTI 64→16 ─────────────────────────────────────────
# Output goes to training/velodyne/ so the directory tree matches what
# fixed_kitti_dataset.py and setupandruntest.py expect.
run_downsample() {
    step "Step 1: Downsampling KITTI 64-beam → 16-beam (VLP-16 simulation)"
    docker exec "${CONTAINER_VELODYNE}" bash -c \
        "mkdir -p '${VEL_KITTI_REDUCED}/training/velodyne' && \
         pixi run python3 ${VEL_SCRIPTS}/downsample_64_to_16.py \
             ${VEL_KITTI_VELODYNE}/training/velodyne ${VEL_KITTI_REDUCED}/training/velodyne --batch"
    log "Downsampled dataset written to ${VEL_KITTI_REDUCED}/training/velodyne"
    
    docker exec "${CONTAINER_VELODYNE}" bash -c \
        "mkdir -p '${VEL_KITTI_REDUCED}/testing/velodyne' && \
         pixi run python3 ${VEL_SCRIPTS}/downsample_64_to_16.py \
             ${VEL_KITTI_VELODYNE}/testing/velodyne ${VEL_KITTI_REDUCED}/testing/velodyne --batch"
    log "Downsampled dataset written to ${VEL_KITTI_REDUCED}/testing/velodyne"
}

# ─── Step 2: KITTI dataset infos ─────────────────────────────────────────────
# Sets up the directory structure needed by fixed_kitti_dataset, then runs
# create_kitti_infos for both original KITTI (if PKLs are missing) and for
# reduced-kitti (always, since the velodyne data just changed).
# Interpolated datasets reuse the reduced-kitti PKLs via setupandruntest.py.
run_kitti_infos() {
    step "Step 2: KITTI dataset infos"

    # ── 2a. Symlink reduced-kitti auxiliary data → original-kitti ─────────────
    # reduced-kitti/training/velodyne already has the downsampled bins.
    # Everything else (calib, images, labels, ImageSets, testing) comes from
    # original-kitti via symlinks so that fixed_kitti_dataset can find them.
    log "Setting up auxiliary symlinks in reduced-kitti..."
    docker exec "${CONTAINER_OPENPCDET}" bash -c "
        set -e
        R='${OPC_KITTI_REDUCED}'
        O='${OPC_KITTI_DATA}'
        mkdir -p \"\$R/training\" \"\$R/testing\"
        ln -sfn \"\$O/ImageSets\"          \"\$R/ImageSets\"
        ln -sfn \"\$O/training/calib\"     \"\$R/training/calib\"
        ln -sfn \"\$O/training/image_2\"   \"\$R/training/image_2\"
        ln -sfn \"\$O/training/label_2\"   \"\$R/training/label_2\"
        [ -d \"\$O/training/planes\" ] && ln -sfn \"\$O/training/planes\" \"\$R/training/planes\" || true
        ln -sfn \"\$O/testing/calib\"      \"\$R/testing/calib\"
        ln -sfn \"\$O/testing/image_2\"    \"\$R/testing/image_2\"
        ln -sfn \"\$O/testing/velodyne\"   \"\$R/testing/velodyne\"
    "
    log "Auxiliary symlinks ready."

    # ── 2b. Original KITTI infos (skip if PKLs already exist) ─────────────────
    local opc_pkl="${OPC_KITTI_DATA}/kitti_infos_train.pkl"
    local has_pkl
    has_pkl=$(docker exec "${CONTAINER_OPENPCDET}" bash -c \
        "[ -f '${opc_pkl}' ] && echo yes || echo no")
    if [[ "${has_pkl}" == "yes" ]]; then
        log "Original KITTI PKLs found — skipping create_kitti_infos."
    else
        log "Creating dataset infos for original KITTI..."
        docker exec "${CONTAINER_OPENPCDET}" bash -c \
            "cd ${OPC_ROOT} && \
             python3 -m pcdet.datasets.kitti.fixed_kitti_dataset \
                 create_kitti_infos ${OPC_CFG_ORIGINAL}"
        log "Original KITTI infos done."
    fi

    # ── 2c. Reduced-kitti infos (always regenerate after downsampling) ─────────
    log "Creating dataset infos for reduced-kitti..."
    docker exec "${CONTAINER_OPENPCDET}" bash -c \
        "cd ${OPC_ROOT} && \
         python3 -m pcdet.datasets.kitti.fixed_kitti_dataset \
             create_kitti_infos ${OPC_CFG_REDUCED}"
    log "Reduced-kitti infos done."
}

# ─── Step 3: Generate interpolated datasets ───────────────────────────────────
# Calls interpolate_bin_batch.py directly in the velodyne container (no ROS2).
# Both splits are processed independently; a split is skipped if its target
# directory already exists and is non-empty.
# Output layout: <cfg_name>/training/velodyne/ and <cfg_name>/testing/velodyne/
# so that setupandruntest.py can find lidar_root/training/velodyne.
run_interpolation() {
    step "Step 3: Generating interpolated datasets"

    local configs
    configs=$(docker exec "${CONTAINER_VELODYNE}" bash -c \
        "ls '${VEL_INTERP_CONFIG_DIR}'/*.yaml 2>/dev/null | sort")

    if [[ -z "${configs}" ]]; then
        log "WARNING: No interpolation configs found in ${VEL_INTERP_CONFIG_DIR}. Skipping."
        return
    fi

    local train_src="${VEL_KITTI_REDUCED}/training/velodyne"
    local test_src="${VEL_KITTI_REDUCED}/testing/velodyne"

    while IFS= read -r cfg_file; do
        [[ -z "${cfg_file}" ]] && continue
        local cfg_name
        cfg_name=$(basename "${cfg_file}" .yaml)
        [[ -n "${SINGLE_CONFIG}" && "${cfg_name}" != "${SINGLE_CONFIG}" ]] && continue

        local dataset_out="${VEL_KITTI_INTERP_BASE}/${cfg_name}"
        local train_out="${dataset_out}/training/velodyne"
        local test_out="${dataset_out}/testing/velodyne"

        echo "------------------------------------------------------------"
        echo " CONFIG: ${cfg_name}"
        echo "------------------------------------------------------------"

        # Ensure dataset folder exists and copy config there (always)
        docker exec "${CONTAINER_VELODYNE}" bash -c \
            "mkdir -p '${dataset_out}' && cp -f '${cfg_file}' '${dataset_out}/'"

        # Check which splits need processing
        local train_skip test_skip
        train_skip=$(docker exec "${CONTAINER_VELODYNE}" bash -c \
            "[[ -d '${train_out}' && -n \"\$(ls -A '${train_out}' 2>/dev/null)\" ]] \
             && echo yes || echo no")
        test_skip=$(docker exec "${CONTAINER_VELODYNE}" bash -c \
            "[[ -d '${test_out}' && -n \"\$(ls -A '${test_out}' 2>/dev/null)\" ]] \
             && echo yes || echo no")

        if [[ "${train_skip}" == "yes" && "${test_skip}" == "yes" ]]; then
            log "  SKIP: both splits already non-empty for ${cfg_name}"
            continue
        fi

        docker exec "${CONTAINER_VELODYNE}" bash -c \
            "mkdir -p '${dataset_out}/training' '${dataset_out}/testing'"

        if [[ "${train_skip}" != "yes" ]]; then
            log "  [1/2] Interpolating TRAIN split for ${cfg_name}..."
            docker exec "${CONTAINER_VELODYNE}" bash -c \
                "pixi run python3 '${VEL_INTERP_SCRIPT}' \
                    '${train_src}' '${train_out}' --config '${cfg_file}'"
        else
            log "  [1/2] SKIP TRAIN: already non-empty"
        fi

        if [[ "${test_skip}" != "yes" ]]; then
            log "  [2/2] Interpolating TEST split for ${cfg_name}..."
            docker exec "${CONTAINER_VELODYNE}" bash -c \
                "pixi run python3 '${VEL_INTERP_SCRIPT}' \
                    '${test_src}' '${test_out}' --config '${cfg_file}'"
        else
            log "  [2/2] SKIP TEST: already non-empty"
        fi

        log "Done: ${cfg_name}"
    done <<< "${configs}"
}

# ─── Step 4: Offline batch evaluations ───────────────────────────────────────
# Runs in openpcdet container (GPU inference, model configs in src/lidar).
#
# setupandruntest.py expects:
#   --dataset-root  DIR   dir containing PKLs, gt_database, calib, label_2, etc.
#   --image-set-root DIR  dir containing ImageSets/
#   --lidar-root    DIR   dir containing training/velodyne and testing/velodyne
#
# Interpolated datasets reuse reduced-kitti PKLs (dataset_root=OPC_KITTI_REDUCED)
# but point to their own velodyne bins (lidar_root=interp/<cfg_name>).
run_batch_eval() {
    # Args: cfg_subdir  dataset_root  imageset_root  lidar_root  dest_dir  dataset_label
    local cfg_subdir="$1" dataset_root="$2" imageset_root="$3" lidar_root="$4" \
          dest_dir="$5" dataset_label="${6:-$(basename "${lidar_root}")}"

    docker exec "${CONTAINER_OPENPCDET}" bash -c "mkdir -p '${dest_dir}'"

    for MODEL in $(printf '%s\n' "${!MODELS[@]}" | sort); do
        [[ -n "${SINGLE_MODEL}" && "${MODEL}" != "${SINGLE_MODEL}" ]] && continue
        read -r CFG CKPT <<< "${MODELS[$MODEL]}"
        log "  [${dataset_label}] Model: ${MODEL}"
        docker exec "${CONTAINER_OPENPCDET}" bash -c \
            "cd ${OPC_ROOT} && \
             python3 ${OPC_TOOLS}/setupandruntest.py \
                --dataset-root   '${dataset_root}' \
                --image-set-root '${imageset_root}' \
                --lidar-root     '${lidar_root}' \
                --cfg_file ${OPC_TOOLS}/cfgs/kitti_models/${cfg_subdir}/${CFG} \
                --batch_size 1 \
                --ckpt ${OPC_PRETRAINED}/${CKPT}"
        local src="${OPC_ROOT}/output/src/lidar/tools/cfgs/kitti_models/${cfg_subdir}/${MODEL}"
        docker exec "${CONTAINER_OPENPCDET}" bash -c \
            "mkdir -p '${dest_dir}/${dataset_label}' && \
             mv '${src}' '${dest_dir}/${dataset_label}/${MODEL}' 2>/dev/null || true"
    done
}

run_offline_evals() {
    step "Step 4: Offline batch evaluations"
    docker exec "${CONTAINER_OPENPCDET}" bash -c \
        "mkdir -p '${OFFLINE_RAW}/original' '${OFFLINE_RAW}/downsampled' \
                   '${OFFLINE_RAW}/interpolated'"

    # Original KITTI: data_root = imageset_root = lidar_root = OPC_KITTI_DATA
    log "--- Original KITTI ---"
    run_batch_eval "original" \
        "${OPC_KITTI_DATA}" "${OPC_KITTI_DATA}" "${OPC_KITTI_DATA}" \
        "${OFFLINE_RAW}/original" "kitti"

    # Reduced KITTI: data_root = imageset_root = lidar_root = OPC_KITTI_REDUCED
    # (has training/velodyne with downsampled bins, plus symlinks to original aux data)
    log "--- Downsampled (reduced-kitti) ---"
    run_batch_eval "downsampled" \
        "${OPC_KITTI_REDUCED}" "${OPC_KITTI_REDUCED}" "${OPC_KITTI_REDUCED}" \
        "${OFFLINE_RAW}/downsampled" "reduced"

    # Interpolated: PKLs from reduced-kitti, velodyne from interpolated dir.
    log "--- Interpolated datasets ---"
    local configs
    configs=$(docker exec "${CONTAINER_OPENPCDET}" bash -c \
        "ls '${OPC_KITTI_INTERP_BASE}' 2>/dev/null | sort" || true)
    while IFS= read -r cfg_name; do
        [[ -z "${cfg_name}" ]] && continue
        [[ -n "${SINGLE_CONFIG}" && "${cfg_name}" != "${SINGLE_CONFIG}" ]] && continue
        local interp_root="${OPC_KITTI_INTERP_BASE}/${cfg_name}"
        log "  Interpolated config: ${cfg_name}"
        run_batch_eval "interpolated" \
            "${OPC_KITTI_REDUCED}" "${OPC_KITTI_REDUCED}" "${interp_root}" \
            "${OFFLINE_RAW}/interpolated" "${cfg_name}"
    done <<< "${configs}"
}

# ─── Step 5: Save per-frame detection bboxes ─────────────────────────────────
# save_detections.py --bin-dir takes the directory of .bin files directly.
run_save_detections() {
    step "Step 5: Saving per-frame detection results (kitti_inspector compatible)"
    docker exec "${CONTAINER_OPENPCDET}" bash -c "mkdir -p '${OFFLINE_RAW}/detections'"

    local datasets=(
        "original:${OPC_KITTI_VELODYNE}"
        "downsampled:${OPC_KITTI_REDUCED_VELODYNE}"
    )

    local configs
    configs=$(docker exec "${CONTAINER_OPENPCDET}" bash -c \
        "ls '${OPC_KITTI_INTERP_BASE}' 2>/dev/null | sort" || true)
    while IFS= read -r cfg_name; do
        [[ -z "${cfg_name}" ]] && continue
        [[ -n "${SINGLE_CONFIG}" && "${cfg_name}" != "${SINGLE_CONFIG}" ]] && continue
        datasets+=("interp_${cfg_name}:${OPC_KITTI_INTERP_BASE}/${cfg_name}/training/velodyne")
    done <<< "${configs}"

    for entry in "${datasets[@]}"; do
        local label="${entry%%:*}"
        local bin_dir="${entry#*:}"

        for MODEL in $(printf '%s\n' "${!MODELS[@]}" | sort); do
            [[ -n "${SINGLE_MODEL}" && "${MODEL}" != "${SINGLE_MODEL}" ]] && continue
            read -r CFG CKPT <<< "${MODELS[$MODEL]}"
            local out="${OFFLINE_RAW}/detections/${label}/${MODEL}"
            log "  save_detections: ${label} / ${MODEL}"
            docker exec "${CONTAINER_OPENPCDET}" bash -c \
                "cd ${OPC_ROOT} && \
                 python3 ${OPC_BATCH}/save_detections.py \
                    --cfg_file  ${OPC_TOOLS}/cfgs/kitti_models/${CFG} \
                    --ckpt      ${OPC_PRETRAINED}/${CKPT} \
                    --bin-dir   '${bin_dir}' \
                    --output-dir '${out}'" || \
            log "  WARNING: save_detections failed for ${label}/${MODEL}"
        done
    done
}

# ─── Step 6: Online (real-time) evaluation ────────────────────────────────────
# Delegates to run_realtime_eval.sh, which handles its own container orchestration.
# --data-path must be the velodyne-container path to the .bin files (the velodyne
# subdirectory, since run_realtime_eval.sh passes it directly to bin_publisher_node).
run_online_eval() {
    step "Step 6: Online (real-time) evaluation"
    docker exec "${CONTAINER_OPENPCDET}" bash -c "mkdir -p '${ONLINE_RAW}'"

    local args="--output-dir ${ONLINE_RAW} \
                --rate ${PUBLISH_RATE} \
                --max-frames ${MAX_FRAMES} \
                --warmup ${WARMUP_FRAMES} \
                --data-type bin \
                --data-path ${VEL_KITTI_REDUCED}/training/velodyne"
    [[ -n "${SINGLE_MODEL}"  ]] && args+=" --model ${SINGLE_MODEL}"
    [[ -n "${SINGLE_CONFIG}" ]] && args+=" --config ${SINGLE_CONFIG}"

    bash "$(dirname "$0")/src/lidar/tools/perf_evaluation/run_realtime_eval.sh" ${args}
}

# ─── Step 7: Generate LaTeX tables ───────────────────────────────────────────
run_latex() {
    step "Step 7: Generating LaTeX tables"
    docker exec "${CONTAINER_OPENPCDET}" bash -c \
        "mkdir -p '${OFFLINE_LATEX}' '${ONLINE_LATEX}'"

    for variant in original downsampled; do
        local src="${OFFLINE_RAW}/${variant}"
        docker exec "${CONTAINER_OPENPCDET}" bash -c \
            "cd ${OPC_ROOT} && \
             python3 ${OPC_BATCH}/generate_latex_single_dataset.py '${src}' && \
             mv '${src}/latex/'*.tex '${OFFLINE_LATEX}/' 2>/dev/null || true"
    done

    docker exec "${CONTAINER_OPENPCDET}" bash -c \
        "cd ${OPC_ROOT} && \
         python3 ${OPC_BATCH}/generate_latex_tables.py '${OFFLINE_RAW}/interpolated' && \
         mv '${OFFLINE_RAW}/interpolated/latex/'*.tex '${OFFLINE_LATEX}/' 2>/dev/null || true"

    docker exec "${CONTAINER_OPENPCDET}" bash -c \
        "cd ${OPC_ROOT} && \
         python3 ${OPC_TOOLS}/perf_evaluation/aggregate_realtime_results.py '${ONLINE_RAW}' && \
         cp '${ONLINE_RAW}/'*.csv '${ONLINE_LATEX}/' 2>/dev/null || true"
}

